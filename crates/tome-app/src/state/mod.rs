//! `[WIP]` 外壳状态层（S3 T011/T015/T030）
//!
//! ## 这一层放什么
//!
//! **可判定的决策**。书架有哪些条目、哪些可见、进度什么时候落盘——这些都有
//! 明确的验收判据（SC-005/009/010），而它们的判定不该依赖一个真实窗口。
//!
//! 视图（[`crate::views`]）只做"把这里算出来的东西画出来"与"把输入翻成意图"。
//! 两者分开后，"1000 册过滤一次要多久"是一次被 `Instant` 包住的函数调用，
//! "往返后滚动位置变没变"是两次方法调用加一次相等比较——**都能进 CI**。
//!
//! ## 为什么不做成全局单例
//!
//! `AppView` 的状态机持有一份实例（`ViewState` 的字段）。单例会让测试之间
//! 互相污染（并行跑的两个测试改同一份状态），而"测试可以并行"是这个仓库
//! 既有的前提（`cargo test -j 2`）。

