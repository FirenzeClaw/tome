//! 宿主 API：FR-005 八类能力的 JS 侧实现
//!
//! # 为什么按 FR-005 的**类别**分模块，而不是按 `java.*` 的方法名分组
//!
//! FR-005b 要求"该能力集 MUST 有一份显式的、可被测试逐项覆盖的清单"。
//! 按类别分模块让清单与代码结构**同构**：对照 FR-005 的八条，能直接
//! 看出每条落在哪个文件、覆盖了多少项。按方法名分组会让"某一类少实现了
//! 一项"变得难以发现（它只是这个文件里的第 47 个函数）。
//!
//! # 与 `bridge` 的分工
//!
//! `bridge` 提供**机制**（如何注册宿主函数、如何抛错、状态放哪）；
//! 本模块提供**内容**（有哪些函数、每个做什么）。故这里的每个子模块
//! 都只关心"这个能力做什么"，不重复实现注册与错误处理的约定。
//!
//! # 覆盖矩阵（FR-005 的八类 → 模块）
//!
//! | FR-005 类别 | 模块 | 任务 |
//! |---|---|---|
//! | 网络（单次/并发批量/下载到缓存/下载到文件） | [`net`] | T036 |
//! | 文本与编码（Base64/URL/十六进制/字符集/简繁） | [`text`] | T037 |
//! | 摘要与加密（MD5/SHA/AES/DES/RSA） | [`crypto`] | T038 |
//! | 结构化数据（JSON/XML/网页标记解析） | [`data`] | T039 |
//! | 正则 + 时间日期 + 杂项（随机/压缩/实体） | [`util`] | T040 |
//! | 宿主状态（缓存/文件/Cookie/外部脚本/变量池/上下文） | [`state`] | T041 |
//! | 不支持的能力（结构化错误） | [`unsupported`] | T042 |
//!
//! [WIP] 各子模块按任务顺序落地。

pub mod unsupported;

