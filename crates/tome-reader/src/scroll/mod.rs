//! [WIP] 滚动模式（T025-T031 / S2-3）
//!
//! | 模块 | 职责 | 需求 |
//! |---|---|---|
//! | [`flow`] | 滚动流排布（连续流 → 视口序列） | FR-020 / FR-021 |
//! | [`map`] | 滚动偏移 ⇄ 字符位置双向映射 | FR-022 / FR-040 |
//!
//! ## 依赖方向
//!
//! ```text
//! paginate（行盒 + 分页） ──→ scroll（本模块）
//! ```
//!
//! scroll **不依赖** render——滚动位置换算是几何计算，必须能在无图形环境下
//! 完整运行（宪法 IV / FR-052）。它也**不自行排版**：行盒一律来自
//! `paginate::page::layout_chapter`，这是 FR-021"不引入第二套坐标"的
//! 结构性保证（没有第二条排版路径可绕过）。
//!
//! ## 两种形态的关系（FR-020/023）
//!
//! 翻页与滚动是**同一份排版结果**的两种切法：
//!
//! | | 切分依据 | 位置单位 |
//! |---|---|---|
//! | 翻页 | 可用高（页高） | 页序号 + 页内偏移 |
//! | 滚动 | 可用高（屏高） | 流偏移 + 屏内偏移 |
//!
//! 两者的**位置主口径都是章内字符区间**（FR-021），像素量只是表达。

