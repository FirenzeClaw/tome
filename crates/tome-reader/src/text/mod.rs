//! `[DONE]` 文本模型与段落切分（T010 / T011）
//!
//! 本模块是排版层的**输入规范化**：把一章原文变成"段落序列 + 位置口径"。
//!
//! | 模块 | 职责 | 需求 |
//! |---|---|---|
//! | [`model`] | 字形簇切分、字符下标口径、可断点表 | FR-003 |
//! | [`paragraph`] | 换行符切分 + 前导全角空格启发式 | FR-001 / FR-002 |
//!
//! ## 位置口径的唯一权威者
//!
//! 本层之上的所有模块（rules / layout / paginate / scroll / trace）一律以
//! [`model::CharIndex`]（Unicode 标量值下标）为单位表达位置。**没有例外**——
//! 一旦某处改用字节偏移，跨子项目的锚点换算就会出现一个看不见的偏移量。

pub mod model;
pub mod paragraph;
