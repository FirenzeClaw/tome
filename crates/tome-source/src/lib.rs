//! # tome-source —— 书源管线
//!
//! 把一份书源定义变成可读的内容，串起全部环节：搜索、发现（分类/榜单）、书籍详情、
//! 目录、正文抓取、内容净化、换源、书源可用性检查。
//!
//! ## 在本项目中的位置
//!
//! - 依赖 `tome-core` / `tome-net` / `tome-store` / `tome-js` / `tome-rule`，
//!   是**唯一发起真实网络请求**的管线（架构决策 A2）。
//! - 正文读取经 `ContentProvider` seam，其下两个 adapter：网络书缓存抓取 / 本地书偏移直读，
//!   使净化管线下游对两者统一（架构决策 A4）。
//!
//! ## 护栏
//!
//! - 遵守书源声明的请求间隔，不得绕过限速（宪法原则 V）。
//! - `search` 返回**流 + 取消令牌**，单源失败是流内条目而非整体失败（架构决策 A6）。
//! - 书源规则本身是不可信输入，边界处必须校验。
//!
//! ## 关键入口
//!
//! 骨架阶段尚无公开 API；Phase 2 起陆续落地。
//!
//! [WIP] 本 crate 当前为空骨架，未含任何实现。

