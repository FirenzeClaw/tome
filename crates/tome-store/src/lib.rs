//! # tome-store —— 存储层
//!
//! 负责全部本地数据持久化：SQLite actor（单写者串行化）、schema 迁移器、各表 DAO、
//! 书籍 Pack 容器、图片缓存，以及配置的类型化注入。
//!
//! ## 在本项目中的位置
//!
//! 实现 `tome-core` 定义的 `StoreHost` 接缝；`tome-source` / `tome-local` 经它读写数据。
//!
//! ## 护栏
//!
//! - 数据库查询全部参数化（宪法原则 V）。
//! - **缓存写入顺序不可颠倒**：内容追加落盘并 fsync **先于**索引事务提交，
//!   反过来会产生悬空引用（FR-030）。
//! - 阅读痕迹（高亮/批注/书签）一律以**字符区间**表达，禁存渲染坐标（FR-028）。
//!
//! ## 关键入口
//!
//! 骨架阶段尚无公开 API；Phase 2 起按 `contracts/seams.md` 落地。
//!
//! [WIP] 本 crate 当前为空骨架，未含任何实现。

